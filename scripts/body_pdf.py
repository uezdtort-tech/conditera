    canvas.drawString(40, A4[1] - 28, 'Уездный кондитер v2.0 — Архитектура ролевой экосистемы')
    # Footer: страница N + дата
    canvas.setFont('FreeSerif', 8.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawRightString(A4[0] - 40, 24, f'Страница {doc.page}')
    canvas.drawString(40, 24, 'Z.ai · Техническая документация · Август 2026')
    canvas.restoreState()

