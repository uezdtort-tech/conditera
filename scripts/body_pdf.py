def add_heading(text, style, level=0, story=None):
    key = f'h_{hashlib.md5(text.encode("utf-8")).hexdigest()[:8]}'
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    if story is not None:
        story.append(p)
    return p

def add_body(text, story, indent=True):
    style = style_body if indent else style_body_noindent
    story.append(Paragraph(text, style))

def add_bullets(items, story):
    for item in items:
        story.append(Paragraph(f'<bullet>&bull;</bullet> {item}', style_bullet))

def add_spacer(h, story):
    story.append(Spacer(1, h))

def add_hr(story, color=None, thickness=0.6):
    story.append(HRFlowable(width='100%', thickness=thickness,
                            color=color or BORDER, spaceBefore=4, spaceAfter=10))

def add_callout(text, story, label='ЗАМЕТКА'):
    p_label = Paragraph(f'<b>{label}</b>', ParagraphStyle(
        name='CalloutLabel', fontName=BOLD_FONT, fontSize=8, leading=10,
        textColor=ACCENT, alignment=TA_LEFT, spaceAfter=2))
    p_body = Paragraph(text, style_callout)
    story.append(KeepTogether([p_label, p_body]))

def make_table(data, col_widths=None, header_rows=1):
    """Создать таблицу с корректными стилями.
    data[0] = header (если header_rows=1)
    Остальные = body rows. Каждая ячейка — строка или Paragraph."""
    rows = []
    for i, row in enumerate(data):
        new_row = []
        for cell in row:
            if isinstance(cell, str):
                if i < header_rows:
                    new_row.append(Paragraph(cell, style_table_header))
                else:
                    new_row.append(Paragraph(cell, style_table_cell))
            else:
                new_row.append(cell)
        rows.append(new_row)
    t = Table(rows, colWidths=col_widths, hAlign='CENTER', repeatRows=header_rows)
    style_list = [
        ('BACKGROUND', (0,0), (-1,header_rows-1), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0,0), (-1,header_rows-1), colors.white),
        ('FONTNAME', (0,0), (-1,header_rows-1), BOLD_FONT),
        ('FONTSIZE', (0,0), (-1,-1), 9.5),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('LEFTPADDING', (0,0), (-1,-1), 6),
        ('RIGHTPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.4, BORDER),
        ('ROWBACKGROUNDS', (0,header_rows), (-1,-1),
            [TABLE_ROW_EVEN, TABLE_ROW_ODD]),
    ]
    t.setStyle(TableStyle(style_list))
    return t

def add_table(data, story, col_widths=None, caption=None, header_rows=1):
    t = make_table(data, col_widths=col_widths, header_rows=header_rows)
    add_spacer(6, story)
    story.append(t)
    if caption:
        story.append(Paragraph(caption, style_caption))
    add_spacer(6, story)

def add_code_block(lines, story):
    text = '<br/>'.join(lines)
    p = Paragraph(text, style_code)
    story.append(p)
    add_spacer(6, story)

