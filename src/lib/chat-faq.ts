// ===== Матчинг =====

/**
 * Найти наиболее подходящий FAQ-топик по тексту сообщения.
 * Возвращает топик с наибольшим числом совпадений ключевых слов.
 * Если ни одно совпадение — возвращает null (нужно эскалировать).
 */
export function matchFaqTopic(message: string): FaqTopic | null {
  const lower = message.toLowerCase();

  let bestMatch: FaqTopic | null = null;
  let bestScore = 0;

  for (const topic of FAQ_TOPICS) {
    let score = 0;
    for (const keyword of topic.keywords) {
      if (lower.includes(keyword)) {
        // Длиннее ключевое слово → выше вес
        score += keyword.length > 5 ? 2 : 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = topic;
    }
  }

  return bestScore > 0 ? bestMatch : null;
}

